export function icon(name, size = 24, cls = '') {
  const g = GRIDS[name];
  if (!g) return '';
  const w = Math.max(...g.map((r) => r.length));
  const h = g.length;
  let rects = '';
  g.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const c = C[row[x]];
      if (c) rects += `<rect x="${x}" y="${y}" width="1" height="1" fill="${c}"/>`;
    }
  });
  const hh = Math.round((size * h) / w);
  return `<svg class="px-icon ${cls}" width="${size}" height="${hh}" viewBox="0 0 ${w} ${h}" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}
